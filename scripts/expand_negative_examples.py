def main(out_path: Path) -> dict:
    available = {p.name for p in POLICY_DIR.glob("*.md")}
    items, missing = [], set()
    for i, (question, sources, pending) in enumerate(CANDIDATES, 1):
        for s in sources:
            if s not in available:
                missing.add(s)
        items.append({
            "candidate_id": f"N{i:02d}",
            "question": question,
            "source_files": sources,
            "applicability_label": "不适用",
            "status": "待人工判定",
            "answer": "",
            "gold_chunk_ids": [],
            "pending_review": pending,
        })
    payload = {
        "generated_by": "scripts/expand_negative_examples.py",
        "purpose": "反事实负例题集扩充候选清单（模板化生成，未做法律判定）",
        "usage": ("人工逐条打开 data/policy_docs/ 原文核对后，填写 answer 与 gold_chunk_ids，"
                  "再并入 rag_benchmark_gold_dataset.json；未填写的条目不得计入评测指标。"),
        "existing_negative_examples": ["Q04", "Q24", "Q29", "Q30"],
        "target_count": 30,
        "candidate_count": len(items),
        "missing_source_files": sorted(missing),
        "candidates": items,
    }
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return payload


