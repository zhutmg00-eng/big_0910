"""敏感性分析的结论必须由扫描结果算出，不能是写死的字符串。

事故背景（评审发现）：`scripts/sensitivity_analysis.py` 原本在 print 与
`--out` 生成的 markdown 里都写了四行**硬编码结论**，其中两条与它自己的输出矛盾：

1. 「±20% 里程直接转化为约 ±20 pp 误差」——实测网格显示效应强不对称：
   里程 +20% → MAPE 上升 +20.72~+21.63 pp；里程 −20% → 只上升 +5.30~+13.55 pp。
   模型对里程确实一阶线性，但误差取的是**绝对值**，绝对值让曲线不再关于基准对称。
2. 「实载率净效应约为 1.3 pp」——没有任何算法能产出 1.3。实测同一里程行内的
   极差是 3.67~5.50 pp，跨全部里程倍数看约 4.59 pp。

把"读图时随手写下的结论"当成"实验得出的结论"是可被判为伪造分析结论的性质问题，
因此这里既测数值正确性，也测"结论串不得重新写死"。
"""
import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPT = REPO_ROOT / "scripts" / "sensitivity_analysis.py"
REPORT = REPO_ROOT / "docs" / "sensitivity_report.md"
LEDGER_PATH = REPO_ROOT / "docs" / "derived_metrics.json"


@pytest.fixture(scope="module")
def script_source():
    return SCRIPT.read_text(encoding="utf-8")


def _code_lines(source: str):
    """只保留会真正输出出去的代码行，剔除注释与模块 docstring。

    本测试文件的 docstring 会引用那些坏字符串来解释事故，同样，脚本里也可能
    用注释记录"这里原本写的是 1.3 pp，已删除"。这些都无害，真正危险的是
    把它们重新放回 print() 或报告正文。
    """
    lines, in_doc = [], False
    for raw in source.splitlines():
        stripped = raw.strip()
        if not in_doc and (stripped.startswith('"""') or stripped.startswith("'''")):
            quote = stripped[:3]
            if stripped.count(quote) == 1:
                in_doc = True
            continue
        if in_doc:
            if '"""' in stripped or "'''" in stripped:
                in_doc = False
            continue
        if stripped.startswith("#"):
            continue
        lines.append(raw)
    return "\n".join(lines)


@pytest.fixture(scope="module")
def script_code(script_source):
    return _code_lines(script_source)


class TestNoHardcodedConclusions:
    """结论段落里不得出现写死的数字，必须走 f-string 插值。"""

    # 这些词出现在同一行里，说明该处是在**否定/警示**这个说法，而不是在陈述它。
    NEGATION_MARKERS = ("不要", "不能", "不得", "不是", "而非", "禁用", "禁止", "不许")

    def _offending_lines(self, code, needles):
        bad = []
        for line in code.splitlines():
            if not any(n in line for n in needles):
                continue
            if any(m in line for m in self.NEGATION_MARKERS):
                continue
            bad.append(line.strip())
        return bad

    def test_no_hardcoded_1_3pp_load_effect(self, script_code):
        """「1.3 pp」是编的，任何形式都不许回到可执行代码里。

        允许的唯一形式是显式否定句（"它不是「1.3 pp」这样的单一常数"），
        因为它正是用来阻止读者沿用这个错误数字的警示语。
        """
        bad = self._offending_lines(script_code, ("1.3 pp", "1.3 个百分点"))
        assert not bad, f"「1.3 pp」被当作结论重新写死：{bad}"

    def test_no_unconditional_pm20_mileage_claim(self, script_code):
        """「±20% 里程 ≈ ±20 pp」这种对称说法不得作为**结论**输出。

        判定方式：该说法出现时，同一行或紧邻上一行必须有否定词。
        脚本里现存的用法是 `"...不能笼统写成「±20% 里程≈±20 个百分点」。"`，
        以及报告正文的 `"不得写成「±20% 里程≈±20 个百分点」"`——两处都在警示。
        """
        lines = script_code.splitlines()
        for idx, line in enumerate(lines):
            if not ("±20 pp" in line or "±20 个百分点" in line):
                continue
            window = line + " " + (lines[idx - 1] if idx else "")
            assert any(m in window for m in self.NEGATION_MARKERS), (
                f"对称里程结论疑似被当成结论输出：{line.strip()[:100]}"
            )

    def test_symmetric_claim_keeps_at_least_one_warning(self, script_source):
        """警示语本身要保留，否则下一个人又会把对称说法写回去。"""
        hits = [
            line for line in script_source.splitlines()
            if "±20 pp" in line or "±20 个百分点" in line
        ]
        assert hits, "脚本应至少保留一条警示，说明不得写成对称形式"

    def test_conclusions_are_computed_from_grid(self, script_source):
        """结论必须由 effects/row_span 这类现算变量拼出。"""
        assert "effects" in script_source and "row_span" in script_source
        # 里程不对称的结论必须同时插入 ±20% 两个方向
        assert "plus20" in script_source and "minus20" in script_source

    def test_report_declares_autogenerated(self):
        """生成物必须自带"本文件自动生成"声明，防止有人手改回去。"""
        if not REPORT.exists():
            pytest.skip("docs/sensitivity_report.md 不存在")
        text = REPORT.read_text(encoding="utf-8")
        assert "自动生成" in text
        assert "现算" in text


class TestRunsAndMatchesLedger:
    """真跑一遍，核对输出与台账一致。"""

    @pytest.fixture(scope="class")
    @classmethod
    def run_output(cls):
        proc = subprocess.run(
            [sys.executable, str(SCRIPT)],
            cwd=str(REPO_ROOT), capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=300,
        )
        assert proc.returncode == 0, f"脚本失败：{proc.stderr[-800:]}"
        return proc.stdout

    def test_baseline_mape_is_4_23(self, run_output):
        assert "基线全样本 MAPE: 4.23%" in run_output

    def test_grid_range_matches_ledger(self, run_output):
        assert "3.04% ~ 29.80%" in run_output

    def test_median_close_to_ledger(self, run_output):
        """脚本中位数与台账 median_pct 的差不得超过 0.01。

        两者不是同一粒度：脚本用未截断的原始 MAPE 求中位数（14.5145），
        台账存的是逐格保留两位后的值（中位数 14.515 → 14.52）。硬要求逐位
        相等会把"正确但粒度不同"误判为错误——历史上就因此改错过一次方向。
        """
        m = re.search(r"中位数 MAPE: (\d+\.\d+)%", run_output)
        assert m, "脚本未打印中位数"
        printed = float(m.group(1))
        ledger = json.loads(LEDGER_PATH.read_text(encoding="utf-8"))["sensitivity"]["median_pct"]
        assert abs(printed - ledger) <= 0.01 + 1e-9, (
            f"脚本中位数 {printed} 与台账 {ledger} 相差超过 0.01，需查是哪一侧算错"
        )

    def test_mileage_effect_reported_asymmetric(self, run_output):
        """必须同时给出 +20% 与 −20% 两个方向，且不能是同一个数。"""
        m = re.search(
            r"里程 \+20% 使 MAPE 上升 \+([\d.]+)~\+([\d.]+) pp，"
            r"里程 −20% 只上升 \+([\d.]+)~\+([\d.]+) pp",
            run_output,
        )
        assert m, f"未输出不对称里程结论：{run_output[-500:]}"
        plus_lo, plus_hi, minus_lo, minus_hi = (float(x) for x in m.groups())
        assert plus_lo > minus_hi, (
            f"+20% 下界 {plus_lo} 应明显高于 -20% 上界 {minus_hi}（不对称性）"
        )
        assert 20.0 < plus_lo < plus_hi < 23.0
        assert 4.0 < minus_lo < minus_hi < 15.0

    def test_load_effect_not_reported_as_1_3(self, run_output):
        """输出里凡是提到 1.3 的地方必须是否定句。"""
        for line in run_output.splitlines():
            if "1.3 pp" in line or "1.3 个百分点" in line:
                assert any(
                    m in line for m in TestNoHardcodedConclusions.NEGATION_MARKERS
                ), f"输出把 1.3 pp 当结论了：{line.strip()[:100]}"